CREATE TABLE ANAGRAFICHE.FORNITORI (
    fornitore_id BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    codice VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    nome_normalizzato VARCHAR(150) NOT NULL UNIQUE,
    attivo BOOLEAN NOT NULL DEFAULT TRUE,
    versione_modifica INTEGER NOT NULL DEFAULT 1,
    creato_il TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggiornato_il TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE ANAGRAFICHE.FORNITORI_ALIAS (
    nome_normalizzato VARCHAR(150) NOT NULL PRIMARY KEY,
    fornitore_id BIGINT NOT NULL REFERENCES ANAGRAFICHE.FORNITORI(fornitore_id)
);
ALTER TABLE TON.POLVERI ADD COLUMN fornitore_id BIGINT;
ALTER TABLE TON.POLVERI ADD CONSTRAINT fk_ton_polveri_fornitore FOREIGN KEY (fornitore_id) REFERENCES ANAGRAFICHE.FORNITORI(fornitore_id);
ALTER TABLE COSTI.ORDINI_POLVERI ADD COLUMN fornitore_id BIGINT;
ALTER TABLE COSTI.ORDINI_POLVERI ADD CONSTRAINT fk_costi_ordini_fornitore FOREIGN KEY (fornitore_id) REFERENCES ANAGRAFICHE.FORNITORI(fornitore_id);

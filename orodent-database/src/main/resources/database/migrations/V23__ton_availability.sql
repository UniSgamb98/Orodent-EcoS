CREATE TABLE TON.DISPONIBILITA_IMPORT (
    import_id BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    nome_file VARCHAR(300) NOT NULL,
    data_riferimento DATE NOT NULL,
    importato_il TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    codici_assenti_zero BOOLEAN NOT NULL,
    righe INTEGER NOT NULL,
    CONSTRAINT ck_ton_disp_tipo CHECK (tipo IN ('DISPONIBILITA','ORDINI')),
    CONSTRAINT ck_ton_disp_righe CHECK (righe>=0)
);
CREATE TABLE TON.DISPONIBILITA_VALORI (
    import_id BIGINT NOT NULL REFERENCES TON.DISPONIBILITA_IMPORT(import_id),
    codice VARCHAR(80) NOT NULL,
    quantita DECIMAL(15,3) NOT NULL,
    PRIMARY KEY (import_id,codice)
);
CREATE TABLE TON.DISPONIBILITA_FONTI (
    tipo VARCHAR(20) NOT NULL PRIMARY KEY,
    import_id BIGINT REFERENCES TON.DISPONIBILITA_IMPORT(import_id),
    versione_modifica INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT ck_ton_disp_fonte CHECK (tipo IN ('DISPONIBILITA','ORDINI'))
);
INSERT INTO TON.DISPONIBILITA_FONTI(tipo) VALUES ('DISPONIBILITA'),('ORDINI');

-- Remove only the original placeholder when unused. Preserve renamed accounts and history.
DELETE FROM ECOS.OPERATORI
WHERE ID='00000000-0000-0000-0000-000000000001'
  AND USERNAME='utente' AND NOME='Operatore ufficio'
  AND NOT EXISTS (SELECT 1 FROM CRM.CLIENTI WHERE OPERATORE_ID=ECOS.OPERATORI.ID)
  AND NOT EXISTS (SELECT 1 FROM CRM.NOTE_CLIENTE WHERE OPERATORE_ID=ECOS.OPERATORI.ID)
  AND NOT EXISTS (SELECT 1 FROM CRM.INTERAZIONI WHERE OPERATORE_ID=ECOS.OPERATORI.ID)
  AND NOT EXISTS (SELECT 1 FROM CRM.CLIENTI_PREFERITI WHERE OPERATORE_ID=ECOS.OPERATORI.ID)
  AND NOT EXISTS (SELECT 1 FROM CRM.VISTE_SALVATE WHERE OPERATORE_ID=ECOS.OPERATORI.ID);

UPDATE ECOS.OPERATORI SET ATTIVO=0
WHERE ID='00000000-0000-0000-0000-000000000001'
  AND USERNAME='utente' AND NOME='Operatore ufficio';

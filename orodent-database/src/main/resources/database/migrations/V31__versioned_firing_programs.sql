CREATE TABLE TON.PROGRAMMI_FAMIGLIE (
    famiglia_id BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY,
    codice VARCHAR(80) NOT NULL,
    versione_modifica INT NOT NULL DEFAULT 1,
    CONSTRAINT pk_ton_prog_fam PRIMARY KEY(famiglia_id),
    CONSTRAINT uq_ton_prog_fam_codice UNIQUE(codice),
    CONSTRAINT ck_ton_prog_fam_token CHECK(versione_modifica>0)
);
INSERT INTO TON.PROGRAMMI_FAMIGLIE(codice) SELECT DISTINCT codice FROM TON.PROGRAMMI_COTTURA;
ALTER TABLE TON.PROGRAMMI_COTTURA ADD COLUMN famiglia_id BIGINT;
ALTER TABLE TON.PROGRAMMI_COTTURA ADD CONSTRAINT fk_ton_programma_famiglia FOREIGN KEY(famiglia_id) REFERENCES TON.PROGRAMMI_FAMIGLIE(famiglia_id);
ALTER TABLE TON.PROGRAMMI_COTTURA ADD COLUMN numero_revisione INT NOT NULL DEFAULT 1;
ALTER TABLE TON.PROGRAMMI_COTTURA ADD COLUMN attivo BOOLEAN NOT NULL DEFAULT TRUE;
UPDATE TON.PROGRAMMI_COTTURA SET famiglia_id=(SELECT f.famiglia_id FROM TON.PROGRAMMI_FAMIGLIE f WHERE f.codice=TON.PROGRAMMI_COTTURA.codice),numero_revisione=versione_modifica,attivo=CASE WHEN stato='RITIRATA' THEN FALSE ELSE TRUE END;
ALTER TABLE TON.PROGRAMMI_COTTURA DROP CONSTRAINT uq_ton_prog_versione;
ALTER TABLE TON.PROGRAMMI_COTTURA ADD CONSTRAINT uq_ton_prog_revisione UNIQUE(codice,numero_versione,numero_revisione);
ALTER TABLE TON.PROGRAMMI_COTTURA ADD CONSTRAINT ck_ton_prog_num_rev CHECK(numero_revisione>0);

CREATE SCHEMA AUDIT;
CREATE TABLE AUDIT.OPERATIONS (
    OPERATION_ID VARCHAR(36) PRIMARY KEY,
    OCCURRED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTOR_ID VARCHAR(36), ACTOR_NAME VARCHAR(240), STATION VARCHAR(128),
    SOURCE VARCHAR(80) NOT NULL, DATABASE_USER VARCHAR(128) NOT NULL
);
CREATE TABLE AUDIT.CHANGES (
    CHANGE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OPERATION_ID VARCHAR(36) NOT NULL,
    TABLE_NAME VARCHAR(80) NOT NULL, ROW_KEY VARCHAR(100) NOT NULL,
    CUSTOMER_ID VARCHAR(36), CUSTOMER_NAME VARCHAR(255),
    CHANGE_KIND VARCHAR(10) NOT NULL CHECK (CHANGE_KIND IN ('INSERT','UPDATE','DELETE')),
    BEFORE_VALUE CLOB, AFTER_VALUE CLOB,
    CONSTRAINT AUDIT_CHANGE_OPERATION FOREIGN KEY (OPERATION_ID) REFERENCES AUDIT.OPERATIONS(OPERATION_ID) ON DELETE CASCADE,
    CONSTRAINT AUDIT_CHANGE_ROW UNIQUE(OPERATION_ID,TABLE_NAME,ROW_KEY)
);
CREATE INDEX AUDIT.IX_OPERATIONS_DATE ON AUDIT.OPERATIONS(OCCURRED_AT);
CREATE INDEX AUDIT.IX_OPERATIONS_ACTOR ON AUDIT.OPERATIONS(ACTOR_ID);
CREATE INDEX AUDIT.IX_CHANGES_CUSTOMER ON AUDIT.CHANGES(CUSTOMER_ID);
CREATE FUNCTION AUDIT.FIELD_VALUE(NAME VARCHAR(128), VAL CLOB) RETURNS CLOB
    LANGUAGE JAVA PARAMETER STYLE JAVA NO SQL CALLED ON NULL INPUT
    EXTERNAL NAME 'com.orodent.ecos.database.audit.AuditValues.field';
CREATE PROCEDURE AUDIT.RECORD_CHANGE(TAB VARCHAR(80), ROW_KEY VARCHAR(100), CUSTOMER_ID VARCHAR(36), OLD_VALUE CLOB, NEW_VALUE CLOB)
    LANGUAGE JAVA PARAMETER STYLE JAVA MODIFIES SQL DATA
    EXTERNAL NAME 'com.orodent.ecos.database.audit.AuditWriter.record';

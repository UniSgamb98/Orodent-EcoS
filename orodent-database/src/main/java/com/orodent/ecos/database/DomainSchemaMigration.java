package com.orodent.ecos.database;

import java.sql.Connection;
import java.sql.SQLException;

/** Moves V1 data in the caller's transaction, preserving identifiers and identity allocation. */
final class DomainSchemaMigration {
    private DomainSchemaMigration() { }

    static void copyData(Connection connection) throws SQLException {
        String customerColumns = "codice_cliente, codice_iso, categoria, listino, agente, "
                + "tipo_cliente, ragione_sociale, importato_il";
        String salesColumns = "vendita_id, sorgente, documento_id, numero_documento, numero_riga, "
                + "data_vendita, codice_cliente, codice_prodotto, descrizione_prodotto, categoria_prodotto, "
                + "quantita, prezzo_unitario, sconto_percentuale, sconto_importo, importo_netto, "
                + "tipo_operazione, canale, agente, importato_il";
        long nextIdentity = nextIdentity(connection);
        try (var statement = connection.createStatement()) {
            statement.executeUpdate("INSERT INTO ANAGRAFICHE.CLIENTI (" + customerColumns + ") SELECT "
                    + customerColumns + " FROM APP.CLIENTI");
            statement.executeUpdate("ALTER TABLE VENDITE.VENDITE_DETTAGLIO ALTER COLUMN vendita_id SET GENERATED BY DEFAULT");
            statement.executeUpdate("INSERT INTO VENDITE.VENDITE_DETTAGLIO (" + salesColumns + ") SELECT "
                    + salesColumns + " FROM APP.VENDITE_DETTAGLIO");
            statement.executeUpdate("ALTER TABLE VENDITE.VENDITE_DETTAGLIO ALTER COLUMN vendita_id SET GENERATED ALWAYS");
            statement.executeUpdate("ALTER TABLE VENDITE.VENDITE_DETTAGLIO ALTER COLUMN vendita_id RESTART WITH " + nextIdentity);
            statement.executeUpdate("INSERT INTO ECOS.ECOS_SCHEMA_HISTORY SELECT * FROM APP.ECOS_SCHEMA_HISTORY");
        }
        verifyRowCount(connection, "APP.CLIENTI", "ANAGRAFICHE.CLIENTI");
        verifyRowCount(connection, "APP.VENDITE_DETTAGLIO", "VENDITE.VENDITE_DETTAGLIO");
    }

    static void removeLegacyTables(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.executeUpdate("DROP TABLE APP.VENDITE_DETTAGLIO");
            statement.executeUpdate("DROP TABLE APP.CLIENTI");
            statement.executeUpdate("DROP TABLE APP.ECOS_SCHEMA_HISTORY");
            // Reserve legacy names without retaining copies of the data. Old bootstrap SQL
            // cannot silently recreate empty APP tables when a downgraded app is started.
            statement.executeUpdate("CREATE SYNONYM APP.CLIENTI FOR ANAGRAFICHE.CLIENTI");
            statement.executeUpdate("CREATE SYNONYM APP.VENDITE_DETTAGLIO FOR VENDITE.VENDITE_DETTAGLIO");
            statement.executeUpdate("CREATE SYNONYM APP.ECOS_SCHEMA_HISTORY FOR ECOS.ECOS_SCHEMA_HISTORY");
        }
    }

    private static long nextIdentity(Connection connection) throws SQLException {
        try (var statement = connection.createStatement();
             var rows = statement.executeQuery("""
                     SELECT SYSCS_UTIL.SYSCS_PEEK_AT_IDENTITY('APP', 'VENDITE_DETTAGLIO'),
                            MAX(vendita_id) FROM APP.VENDITE_DETTAGLIO
                     """)) {
            rows.next();
            long next = rows.getLong(1);
            if (rows.wasNull()) throw new SQLException("Sequenza vendite esaurita: migrazione annullata.");
            long maximum = rows.getLong(2);
            if (!rows.wasNull()) {
                if (maximum == Long.MAX_VALUE) throw new SQLException("Identificativi vendite esauriti: migrazione annullata.");
                next = Math.max(next, maximum + 1);
            }
            return next;
        }
    }

    private static void verifyRowCount(Connection connection, String source, String destination) throws SQLException {
        try (var statement = connection.createStatement(); var rows = statement.executeQuery(
                "SELECT (SELECT COUNT(*) FROM " + source + "), (SELECT COUNT(*) FROM " + destination + ") FROM SYSIBM.SYSDUMMY1")) {
            rows.next();
            if (rows.getLong(1) != rows.getLong(2)) throw new SQLException("Copia incompleta di " + source);
        }
    }
}
